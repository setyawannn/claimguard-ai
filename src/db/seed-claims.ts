function q(value: string | null | undefined): string {
  if (value === undefined || value === null) return 'NULL'
  return `'${value.replaceAll("'", "''")}'`
}

function generateSeedSql() {
  const lines: string[] = []

  for (const h of HOSPITALS) {
    lines.push(
      `INSERT INTO hospitals (id, code, name, facility_type, branch_code, director_name, bed_capacity, bor_total_pct, bor_cardio_vip_pct, compliance_score, compliance_grade, pilar_bor_score, pilar_coding_score, pilar_fast_track_pct, pilar_response_score, tgr_burden_idr, pks_expires_at, pks_status, dominant_typology) VALUES (${q(h.id)}, ${q(h.code)}, ${q(h.name)}, ${q(h.facilityType)}, ${q(h.branchCode)}, ${q(h.directorName)}, ${h.bedCapacity}, ${h.borTotalPct}, ${h.borCardioVipPct}, ${h.complianceScore}, ${q(h.complianceGrade)}, ${h.pilarBorScore}, ${h.pilarCodingScore}, ${h.pilarFastTrackPct}, ${h.pilarResponseScore}, ${h.tgrBurdenIdr}, ${q(h.pksExpiresAt)}, ${q(h.pksStatus)}, ${q(h.dominantTypology)}) ON CONFLICT(id) DO UPDATE SET name=excluded.name, compliance_score=excluded.compliance_score, compliance_grade=excluded.compliance_grade, tgr_burden_idr=excluded.tgr_burden_idr, pks_status=excluded.pks_status, dominant_typology=excluded.dominant_typology;`,
    )
  }

  for (const d of DOCTORS) {
    lines.push(
      `INSERT INTO doctors (id, code, name, specialty, primary_hospital_id, practice_facility_count, repeat_procedure_ratio_pct, peer_avg_ratio_pct, consecutive_rejections) VALUES (${q(d.id)}, ${q(d.code)}, ${q(d.name)}, ${q(d.specialty)}, ${q(d.primaryHospitalId)}, ${d.practiceFacilityCount}, ${d.repeatProcedureRatioPct}, ${d.peerAvgRatioPct}, ${d.consecutiveRejections}) ON CONFLICT(id) DO UPDATE SET name=excluded.name, specialty=excluded.specialty, consecutive_rejections=excluded.consecutive_rejections;`,
    )
  }

  for (const c of CLAIMS) {
    const composite = calculateCompositeRiskScore({
      scoreMedical: c.scoreMedical,
      scoreStatistical: c.scoreStatistical,
      scoreNetwork: c.scoreNetwork,
    })
    const cardHash = `sha256-${c.id}`
    const evidence = JSON.stringify({
      signalSummary: c.signalSummary,
      scoreBreakdown: {
        medical: composite.scoreMedical,
        statistical: composite.scoreStatistical,
        network: composite.scoreNetwork,
      },
    })

    lines.push(
      `INSERT INTO claims (id, no_sep, patient_alias, patient_card_hash, patient_nik_masked, patient_gender, patient_age, admission_date, discharge_date, los_days, service_type, care_class, hospital_id, referring_facility, doctor_id, icd10_primary, icd10_secondary_json, icd9_procedures_json, inacbg_code, inacbg_description, tariff_idr, peer_avg_tariff_idr, hospital_real_cost_idr, score_medical, score_statistical, score_network, risk_score, risk_zone, fraud_typology, signal_summary, evidence_json, status, sla_due_at, hospital_response_note, verified_by, decision_note) VALUES (${q(c.id)}, ${q(c.noSep)}, ${q(c.patientAlias)}, ${q(cardHash)}, ${q(c.patientNikMasked)}, ${q(c.patientGender)}, ${c.patientAge}, ${q(c.admissionDate)}, ${q(c.dischargeDate)}, ${c.losDays}, ${q(c.serviceType)}, ${c.careClass}, ${q(c.hospitalId)}, ${q(c.referringFacility)}, ${q(c.doctorId)}, ${q(c.icd10Primary)}, '[]', '[]', ${q(c.inacbgCode)}, ${q(c.inacbgDescription)}, ${c.tariffIdr}, ${c.peerAvgTariffIdr}, ${c.hospitalRealCostIdr}, ${composite.scoreMedical}, ${composite.scoreStatistical}, ${composite.scoreNetwork}, ${composite.riskScore}, ${q(composite.riskZone)}, ${q(c.fraudTypology)}, ${q(c.signalSummary)}, ${q(evidence)}, ${q(c.status)}, ${q(c.slaDueAt)}, ${q(c.hospitalResponseNote)}, ${q(c.verifiedBy)}, ${q(c.decisionNote)}) ON CONFLICT(id) DO UPDATE SET risk_score=excluded.risk_score, risk_zone=excluded.risk_zone, status=excluded.status, sla_due_at=excluded.sla_due_at, signal_summary=excluded.signal_summary;`,
    )
  }

  const outPath = resolve(process.cwd(), 'drizzle/seed-claims.sql')
  writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8')
  console.log(
    `Generated ${HOSPITALS.length} hospitals, ${DOCTORS.length} doctors, ${CLAIMS.length} claims -> ${outPath}`,
  )
}

